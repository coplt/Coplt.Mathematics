using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Coplt.Analyzers.Generators;

/// <summary>
/// Generates the swizzle interfaces. Every combination of the components is declared as a get interface and a
/// set interface, the digits of the name are the indices of the components, so <c>01</c> is <c>xy</c>. The two
/// spellings of a combination, <c>xyzw</c> and <c>rgba</c>, are declared on the same interface. The interfaces
/// are covariant for the getters and contravariant for the setters, a vector type implements every combination
/// it has and generic code can ask for the members it needs. The scattered interfaces are collected by the
/// interfaces of <c>GenForVec</c>, one for every size of the vector itself.
/// </summary>
[Generator]
public class VectorSwizzleGenerator : IIncrementalGenerator
{
    // the swizzle interfaces live in their own namespace so they do not clutter the vector interfaces
    public const string SwizzleNamespace = "Coplt.Mathematics.Generics.Swizzle";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
        {
            for (var length = 2; length <= 4; length++)
            {
                ctx.AddSource(
                    $"{SwizzleNamespace}.IVectorSwizzle{length}.g.cs",
                    SourceText.From(Gen(length), Encoding.UTF8));
            }

            ctx.AddSource(
                $"{SwizzleNamespace}.IVectorSwizzleForVec.g.cs",
                SourceText.From(GenForVec(), Encoding.UTF8));
        });
    }

    private static string Gen(int length)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {SwizzleNamespace};");
        sb.AppendLine();

        // every combination of the components, 00..00 is the first one and 33..33 the last
        var combinations = 1;
        for (var i = 0; i < length; i++) combinations *= 4;
        for (var combination = 0; combination < combinations; combination++)
        {
            var digits = new StringBuilder(length);
            var xyzw = new StringBuilder(length);
            var rgba = new StringBuilder(length);
            var indices = new int[length];
            for (var i = 0; i < length; i++)
            {
                var index = combination >> (2 * (length - 1 - i)) & 3;
                indices[i] = index;
                digits.Append((char)('0' + index));
                xyzw.Append(Typ.xyzw[index]);
                rgba.Append(Typ.rgba[index]);
            }

            var d = digits.ToString();
            var s = xyzw.ToString();
            var c = rgba.ToString();

            // a member of a swizzle interface is static because the member of the type is a property of the
            // vector itself, so the interface names the type of the vector beside the type of the combination
            sb.AppendLine($"/// <summary>The <c>{s}</c> and <c>{c}</c> swizzle of a vector, its type is <typeparamref name=\"TOut\"/></summary>");
            sb.AppendLine("/// <typeparam name=\"TSelf\">The type of the vector itself</typeparam>");
            sb.AppendLine("/// <typeparam name=\"TOut\">The type of the combination</typeparam>");
            sb.AppendLine($"public interface IVectorGetSwizzle{d}<TSelf, out TOut> where TSelf : unmanaged");
            sb.AppendLine("{");
            sb.AppendLine($"    /// <summary>Returns the <c>{s}</c> swizzle of <paramref name=\"self\"/></summary>");
            sb.AppendLine("    /// <param name=\"self\">The vector</param>");
            sb.AppendLine($"    /// <returns>The <c>{s}</c> combination of the components of <paramref name=\"self\"/></returns>");
            sb.AppendLine($"    public static abstract TOut get_{s}(in TSelf self);");
            sb.AppendLine();
            sb.AppendLine($"    /// <summary>Returns the <c>{c}</c> swizzle of <paramref name=\"self\"/>, it is the same as <see cref=\"get_{s}\"/></summary>");
            sb.AppendLine("    /// <param name=\"self\">The vector</param>");
            sb.AppendLine($"    /// <returns>The <c>{c}</c> combination of the components of <paramref name=\"self\"/></returns>");
            sb.AppendLine($"    public static abstract TOut get_{c}(in TSelf self);");
            sb.AppendLine("}");
            sb.AppendLine();

            // a combination with a repeated index cannot be written by any vector, so it never has a set
            // interface, the setters of the interfaces that collect them keep the same condition
            var distinct = true;
            for (var i = 0; i < length && distinct; i++)
            {
                for (var j = i + 1; j < length; j++)
                {
                    if (indices[i] != indices[j]) continue;
                    distinct = false;
                    break;
                }
            }

            if (!distinct) continue;

            sb.AppendLine($"/// <summary>The <c>{s}</c> and <c>{c}</c> swizzle of a vector, a vector assigns <typeparamref name=\"TIn\"/> to it</summary>");
            sb.AppendLine("/// <typeparam name=\"TSelf\">The type of the vector itself</typeparam>");
            sb.AppendLine("/// <typeparam name=\"TIn\">The type of the combination</typeparam>");
            sb.AppendLine($"public interface IVectorSetSwizzle{d}<TSelf, in TIn> where TSelf : unmanaged");
            sb.AppendLine("{");
            sb.AppendLine($"    /// <summary>Sets the <c>{s}</c> swizzle of <paramref name=\"self\"/> to <paramref name=\"value\"/></summary>");
            sb.AppendLine("    /// <param name=\"self\">The vector</param>");
            sb.AppendLine($"    /// <param name=\"value\">The <c>{s}</c> combination the vector takes</param>");
            sb.AppendLine($"    public static abstract void set_{s}(ref TSelf self, TIn value);");
            sb.AppendLine();
            sb.AppendLine(
                $"    /// <summary>Sets the <c>{c}</c> swizzle of <paramref name=\"self\"/> to <paramref name=\"value\"/>, it is the same as <see cref=\"set_{s}\"/></summary>");
            sb.AppendLine("    /// <param name=\"self\">The vector</param>");
            sb.AppendLine($"    /// <param name=\"value\">The <c>{c}</c> combination the vector takes</param>");
            sb.AppendLine($"    public static abstract void set_{c}(ref TSelf self, TIn value);");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    /// <summary>
    /// Generates the interfaces that collect every swizzle interface a vector of a size has to implement. The
    /// first type parameter is the type of the combination with the same size as the vector and the other ones
    /// are the types of the other sizes, a setter only exists for the combinations without a repeated index so
    /// a short vector may have no setter for a longer combination.
    /// </summary>
    private static string GenForVec()
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {SwizzleNamespace};");
        sb.AppendLine();

        for (var size = 2; size <= 4; size++)
        {
            EmitForVec(sb, size, false);
            EmitForVec(sb, size, true);
        }

        return sb.ToString();
    }

    private static void EmitForVec(StringBuilder sb, int size, bool set)
    {
        var kind = set ? "Set" : "Get";
        // the combination with the same size as the vector returns the vector itself
        var self = set ? "TIn" : "TSelf";

        // the lengths that have a member together with the type of that member, a setter needs every index
        // of the combination to be distinct so a longer combination may not have one
        var lengths = new List<int>();
        var types = new List<string>();
        var others = new List<string>();
        for (var length = 2; length <= 4; length++)
        {
            if (Combinations(size, length, set).Count == 0) continue;
            lengths.Add(length);
            if (length == size)
            {
                types.Add(self);
            }
            else
            {
                var type = $"TVec{length}";
                types.Add(type);
                others.Add(type);
            }
        }

        // the same sized type is the first type parameter, the other ones follow from the short to the long
        var parameters = new List<string> { self };
        parameters.AddRange(others);

        var members = new List<string>();
        for (var i = 0; i < lengths.Count; i++)
        {
            foreach (var digits in Combinations(size, lengths[i], set))
            {
                members.Add($"IVector{kind}Swizzle{digits}<{self}, {types[i]}>");
            }
        }

        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Every swizzle interface a {size} component vector has to implement");
        sb.AppendLine("/// <para>The first type parameter is the type of the same sized combination, the ones after it are");
        sb.AppendLine("/// the types of the other sizes, from the short to the long</para>");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public interface IVector{kind}SwizzleForVec{size}<{string.Join(", ", parameters)}> :");
        for (var i = 0; i < members.Count; i++)
        {
            sb.AppendLine($"    {members[i]}{(i == members.Count - 1 ? "" : ",")}");
        }

        // the type of the vector itself is the first parameter of every interface the collector names
        sb.AppendLine($"    where {self} : unmanaged");
        sb.AppendLine("{");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    /// <summary>
    /// The digits of every combination of the indices of an <paramref name="alphabet"/> sized vector. The digits
    /// are the index of the component in the vector, so for the size 3 the combination 12 is xy and 20 is zx, and
    /// <paramref name="distinct"/> keeps only the combinations that use every index at most once.
    /// </summary>
    private static List<string> Combinations(int alphabet, int length, bool distinct)
    {
        var result = new List<string>();
        var count = 1;
        for (var i = 0; i < length; i++) count *= 4;
        var digits = new char[length];
        for (var combination = 0; combination < count; combination++)
        {
            var valid = true;
            for (var i = 0; i < length; i++)
            {
                var index = combination >> (2 * (length - 1 - i)) & 3;
                if (index >= alphabet)
                {
                    valid = false;
                    break;
                }

                digits[i] = (char)('0' + index);
            }

            if (!valid) continue;
            if (distinct)
            {
                for (var i = 0; i < length && valid; i++)
                {
                    for (var j = i + 1; j < length; j++)
                    {
                        if (digits[i] != digits[j]) continue;
                        valid = false;
                        break;
                    }
                }
            }

            if (valid) result.Add(new string(digits));
        }

        return result;
    }
}
