using System;
using System.Collections.Generic;
using System.Text;

namespace Coplt.Analyzers.Generators;

/// <summary>
/// The emission helpers shared by the base part and the arithmetic part of <see cref="VectorGenerator"/>.
/// </summary>
internal static class VectorGenShared
{
    /// <summary>
    /// Makes the reference to a generic interface. A reference cannot carry the type arguments of a constructed
    /// interface, so the reference names the interface with the type parameters it declares and its text shows
    /// the constructed interface.
    /// </summary>
    /// <param name="name">The name of the interface without its type arguments</param>
    /// <param name="parameters">The names of the type parameters the interface declares</param>
    /// <param name="args">The type arguments of the constructed interface</param>
    /// <returns>The reference</returns>
    public static string IfaceRef(string name, List<string> parameters, List<string> args)
    {
        // the arguments are shown in the text of the reference and every one of them is a reference of its own
        var text = new StringBuilder();
        for (var i = 0; i < args.Count; i++)
        {
            if (i != 0) text.Append(", ");
            text.Append($"<see cref=\"{args[i]}\"/>");
        }

        return $"<see cref=\"{name}{{{string.Join(",", parameters)}}}\">{name}&lt;{text}&gt;</see>";
    }

    /// <summary>
    /// The name of the field that keeps the value of a 64 bit vector. The <c>vector</c> property of the vector
    /// reinterprets it, so the value of the vector does not have to go through a 64 bit vector type.
    /// </summary>
    public const string Vector64Field = "_vector";

    /// <summary>
    /// The 128 bit value of a 64 bit vector, its field is widened by the utility of the vector type.
    /// </summary>
    /// <param name="self">The prefix of the vector, empty for the vector itself</param>
    /// <param name="scalar">The type of a component of the 128 bit register</param>
    /// <returns>The raw simd expression of the value</returns>
    public static string Load64(string self, string scalar) => $"{self}{Vector64Field}.Load64<{scalar}>()";

    /// <summary>
    /// Builds a 64 bit vector from a 128 bit expression, the lower 64 bits of it are the value of the vector.
    /// </summary>
    /// <param name="expr">The raw simd expression of the result</param>
    /// <returns>The construction of the result</returns>
    public static string From128(string expr) => $"new() {{ {Vector64Field} = ({expr}).AsUInt64()[0] }}";

    /// <summary>
    /// Returns the members of a generated file with the empty lines of it normalized: no two empty lines follow
    /// each other and the marker of a region is separated from the lines around it by an empty line.
    /// </summary>
    /// <param name="text">The members of the file</param>
    /// <returns>The normalized members</returns>
    public static string Normalize(string text)
    {
        var sb = new StringBuilder();
        // the last line of the output is empty and the last one is the marker of a region
        var empty = false;
        var marker = false;
        foreach (var line in text.Replace("\r\n", "\n").Split('\n'))
        {
            if (line.Length == 0)
            {
                if (empty) continue;
                empty = true;
                sb.AppendLine();
                continue;
            }

            var isMarker = line.TrimStart().StartsWith("#region") || line.TrimStart().StartsWith("#endregion");
            // a region marker stands between two empty lines, so a blank line opens it and the members after it
            // start under another one
            if (!empty && (isMarker || marker)) sb.AppendLine();
            marker = isMarker;
            empty = false;
            sb.AppendLine(line);
        }

        return sb.ToString();
    }

    /// <summary>
    /// Emits the header every generated vector file starts with.
    /// </summary>
    /// <param name="sb">The builder of the file</param>
    /// <param name="simdHelpers">True when the file uses the helpers of <c>Coplt.Mathematics.Simd</c></param>
    /// <param name="jsonHelpers">True when the file uses the types of <c>System.Text.Json</c></param>
    /// <param name="ns">The namespace of the file, the one of the vectors when it is null</param>
    public static void FileHeader(
        StringBuilder sb, bool simdHelpers, bool jsonHelpers = false, string? ns = null)
    {
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine("using System.Runtime.Intrinsics;");
        // the json members of a vector need the serializer types, only the files that carry them import it
        if (jsonHelpers)
        {
            sb.AppendLine("using System.Text.Json;");
            sb.AppendLine("using System.Text.Json.Serialization;");
        }

        sb.AppendLine("using Coplt.Mathematics;");
        sb.AppendLine("using Coplt.Mathematics.Generics;");
        // the algebra library is reached through an alias, its interfaces are the ones the members of a vector
        // implement: the generics namespace still carries the families that are migrated beside them
        sb.AppendLine("using Algebras = Coplt.Mathematics.Algebras;");
        if (simdHelpers) sb.AppendLine("using Coplt.Mathematics.Simd;");
        sb.AppendLine("using Coplt.Shader;");
        sb.AppendLine();
        sb.AppendLine($"namespace {ns ?? VectorGenerator.VecNamespace};");
    }

    /// <summary>
    /// Returns the names of the components of a vector of <paramref name="size"/> components.
    /// </summary>
    /// <param name="size">The number of components of the vector</param>
    /// <returns>The name of every component</returns>
    public static string[] Components(int size)
    {
        var comp = new string[size];
        for (var i = 0; i < size; i++) comp[i] = Typ.xyzw[i];
        return comp;
    }

    /// <summary>
    /// The type of every value of the algebra by the name of it, the conversions of <see cref="Typ.ExplicitConverts"/>
    /// and <see cref="Typ.ImplicitConverts"/> name the target of a conversion with it.
    /// </summary>
    public static readonly Dictionary<string, Typ> ConvTypes = BuildConvTypes();

    private static Dictionary<string, Typ> BuildConvTypes()
    {
        var map = new Dictionary<string, Typ>();
        foreach (var typ in Typ.Typs) map[typ.name] = typ;
        return map;
    }

    /// <summary>
    /// Returns the conversions of the kind of a component: the target of every conversion of
    /// <see cref="Typ.ExplicitConverts"/> and <see cref="Typ.ImplicitConverts"/> of it beside the name of the kind
    /// of the conversion, which is <c>explicit</c> or <c>implicit</c>. Every value that names the kind of a
    /// component converts the same way, so a vector and a matrix of the kind of a component share the table.
    /// </summary>
    /// <param name="typ">The type of the component</param>
    /// <returns>The conversions of the kind of the component</returns>
    public static List<(string Kind, Typ Target)> ConvTargets(Typ typ)
    {
        var targets = new List<(string Kind, Typ Target)>();
        if (Typ.ExplicitConverts.TryGetValue(typ.name, out var explicitTargets))
        {
            foreach (var name in explicitTargets)
            {
                if (ConvTypes.TryGetValue(name, out var target)) targets.Add(("explicit", target));
            }
        }

        if (Typ.ImplicitConverts.TryGetValue(typ.name, out var implicitTargets))
        {
            foreach (var name in implicitTargets)
            {
                if (ConvTypes.TryGetValue(name, out var target)) targets.Add(("implicit", target));
            }
        }

        return targets;
    }

    /// <summary>
    /// True when the vector has a storage variant. Only the 2 component vectors whose value is 64 bits wide
    /// and the 3 component ones have one: the first ones keep the exact bits of their value instead of a padded
    /// 128 bit register, the last ones keep their components in fields and have no register at all.
    /// </summary>
    /// <param name="typ">The type of the vector</param>
    /// <param name="size">The number of components of the vector</param>
    /// <returns>True when the storage variant exists</returns>
    public static bool HasStorageVariant(Typ typ, int size) =>
        typ.arith && typ.simd && (size == 3 || (size == 2 && 8 * typ.size * 2 == 64));

    /// <summary>
    /// Returns the name of a vector, the storage variant of a vector has the <c>s</c> suffix.
    /// </summary>
    /// <param name="typ">The type of the vector</param>
    /// <param name="size">The number of components of the vector</param>
    /// <param name="storeVariant">True for the storage variant of the vector</param>
    /// <returns>The name of the vector</returns>
    public static string VecName(Typ typ, int size, bool storeVariant) =>
        storeVariant ? $"{typ.name}{size}s" : $"{typ.name}{size}";

    /// <summary>
    /// The name of every whole number the algebra of a value reaches: the value of the constant of a name is the
    /// number of the position of it in the list, so the zero of the kind of a value is the first of them and the
    /// ten of it is the last one.
    /// </summary>
    public static readonly string[] NumberNames =
        { "Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten" };

    /// <summary>
    /// Returns the literal of the whole number at a position of <see cref="NumberNames"/>, which is the value of
    /// the constant of the name of it: the zero of a type is the default of it and holds no literal of its own.
    /// </summary>
    /// <param name="scalar">The type of the component of the value</param>
    /// <param name="position">The position of the number</param>
    /// <returns>The literal of the number</returns>
    public static string NumberValue(string scalar, int position) =>
        position == 0 ? "default" : ScalarOps.Number(scalar, position.ToString());

    /// <summary>
    /// Returns the literal of the negative of the whole number at a position of <see cref="NumberNames"/>, which
    /// is the value of the constant the name of it is written with <c>Negative</c> in front of it. A half encloses
    /// the number of it in the parentheses of the cast, which a cast of a negative value needs.
    /// </summary>
    /// <param name="scalar">The type of the component of the value</param>
    /// <param name="position">The position of the number</param>
    /// <returns>The literal of the negative of the number</returns>
    public static string NegativeValue(string scalar, int position) => scalar == "half"
        ? $"(half)(-{position}f)"
        : $"-{ScalarOps.Number(scalar, position.ToString())}";

    /// <summary>
    /// Returns the literal of the constant of the denominator of a quotient of the kind of
    /// <paramref name="scalar"/>, which is the smallest value that a divisor of a quotient of the kind of it may
    /// be. The value is not a constant of the ieee 754 standard, the library picks one for every kind: the value
    /// of a kind is a power of ten that is large enough to keep the quotient of two values of it meaningful.
    /// </summary>
    /// <param name="scalar">The type of the component of the value</param>
    /// <returns>The literal of the constant</returns>
    public static string DenomEpsilonValue(string scalar) => scalar switch
    {
        "float" => "1e-8f",
        "double" => "1e-16",
        _ => "(half)1e-3f",
    };

    /// <summary>
    /// Returns the literal of the smallest positive normal value of the kind of <paramref name="scalar"/>, which
    /// is the smallest value of the kind of it that the ieee 754 standard calls a normal number. The component
    /// type of a vector does not carry the constant the way it carries the other ones of the standard, so the
    /// value of the kind of it is written out.
    /// </summary>
    /// <param name="scalar">The type of the component of the value</param>
    /// <returns>The literal of the constant</returns>
    public static string MinNormalValue(string scalar) => scalar switch
    {
        "float" => "1.175494351e-38f",
        "double" => "2.2250738585072014e-308",
        _ => "(half)6.103515625e-5f",
    };

    /// <summary>
    /// Returns the names of the interfaces of the dispatch of the kind of a value in the algebra library: the one
    /// of a number beside the one of the floating point kind, which every floating point type of the library
    /// names, a half as well.
    /// </summary>
    /// <param name="typ">The type of the component of the value</param>
    /// <returns>The names of the interfaces of the dispatch</returns>
    public static string[] DispatchIfaces(Typ typ) => typ.f
        ? new[]
        {
            "INumberAlgebraDispatch", "IFloatingPointAlgebraDispatch",
        }
        : new[] { "INumberAlgebraDispatch" };

    /// <summary>
    /// Returns the name of the interface of the dispatch of a kind of a value as the type of the value names it:
    /// the dispatch of the kind of a number reaches the values of the kind of it and the ones that take a
    /// component of the value beside it, so it names the type of a component as well, and the one of the kind of
    /// a floating point number reaches the values of the kind of it alone, so it names the type of the value.
    /// </summary>
    /// <param name="family">The name of the family of the dispatch</param>
    /// <param name="type">The name of the type of the value</param>
    /// <param name="item">The name of the type of a single component</param>
    /// <returns>The name of the interface of the dispatch</returns>
    public static string DispatchIface(string family, string type, string item) => family == "INumberAlgebraDispatch"
        ? $"Algebras.Generics.{family}<{type}, {item}>"
        : $"Algebras.Generics.{family}<{type}>";

    /// <summary>
    /// Returns the name of the type of the bool value that has the same shape as a vector of a kind, which is
    /// the letter of the kind of it, the width of a single component of it and the count of its components.
    /// </summary>
    /// <param name="typ">The type of the component of the value</param>
    /// <param name="size">The number of the components of the vector</param>
    /// <returns>The name of the type of the bool value</returns>
    public static string BoolName(Typ typ, int size) => $"b{typ.size * 8}v{size}";

    /// <summary>
    /// Returns the name of the type of a single component of the bool value of a kind, which is the letter of
    /// the kind of it and the width of a single component of it.
    /// </summary>
    /// <param name="typ">The type of the component of the value</param>
    /// <returns>The name of the type of a single component of the bool value</returns>
    public static string BoolScalarName(Typ typ) => $"b{typ.size * 8}";

    /// <summary>
    /// Returns the name of the interface of the dispatch of the bool value of a floating point value: the bool
    /// value of a value has a shape of its own, which the type of the value does not name, so the dispatch of it
    /// names the type of the bool value beside the type of the value.
    /// </summary>
    /// <param name="type">The name of the type of the value</param>
    /// <param name="boolType">The name of the type of the bool value</param>
    /// <returns>The name of the interface of the dispatch</returns>
    public static string DispatchBoolIface(string type, string boolType) =>
        $"Algebras.Generics.IFloatingPointAlgebraBoolDispatch<{type}, {boolType}>";

    /// <summary>
    /// Returns the bit size of the register that keeps the value of a vector, 0 when the vector has no register.
    /// A 3 or 4 component vector is padded to 4 lanes and the 2 component ones keep the exact width of their
    /// value beside the storage variant of a 4 byte component vector, whose value is widened to 128 bits because
    /// the 64 bit register of it is not accelerated on every platform. The storage variant of a vector keeps its
    /// components in fields, it has no register at all.
    /// </summary>
    /// <param name="typ">The type of the vector</param>
    /// <param name="size">The number of components of the vector</param>
    /// <param name="storeVariant">True for the storage variant of the vector</param>
    /// <returns>The bit size of the register</returns>
    public static int Register(Typ typ, int size, bool storeVariant)
    {
        if (storeVariant) return 0;
        if (!typ.simd) return 0;
        if (size == 2)
        {
            var exact = 8 * typ.size * 2;
            return exact == 64 ? 128 : exact;
        }

        return 8 * typ.size * 4;
    }

    /// <summary>
    /// True when the value of the vector is kept in a 64 bit register behind a raw <c>ulong</c> field instead of
    /// a <c>Vector64</c> field, the property of the vector reinterprets the bits of it. No vector keeps its value
    /// that way: the storage variant of a 2 component vector keeps its components in fields beside the storage
    /// variant of a 3 component one.
    /// </summary>
    /// <param name="typ">The type of the vector</param>
    /// <param name="size">The number of components of the vector</param>
    /// <param name="storeVariant">True for the storage variant of the vector</param>
    /// <returns>True when the value is kept in a raw ulong field</returns>
    public static bool Uses64(Typ typ, int size, bool storeVariant) => Register(typ, size, storeVariant) == 64;

    /// <summary>
    /// True when the vector is backed by a hardware accelerated register.
    /// </summary>
    /// <param name="typ">The type of the vector</param>
    /// <param name="size">The number of components of the vector</param>
    /// <param name="storeVariant">True for the storage variant of the vector</param>
    /// <returns>True when the vector is backed by a register</returns>
    public static bool Simd(Typ typ, int size, bool storeVariant) => Register(typ, size, storeVariant) != 0;

    /// <summary>
    /// Returns the size of the value of a vector in bytes. The value of a vector that has no register is kept in
    /// fields, a 3 component one is padded to the width of a 4 component one.
    /// </summary>
    /// <param name="typ">The type of the vector</param>
    /// <param name="size">The number of components of the vector</param>
    /// <param name="storeVariant">True for the storage variant of the vector</param>
    /// <returns>The size of the value of the vector in bytes</returns>
    public static int ByteSize(Typ typ, int size, bool storeVariant) =>
        Simd(typ, size, storeVariant)
            ? Register(typ, size, storeVariant) / 8
            : typ.size * (size == 3 ? 4 : size);

    /// <summary>
    /// Returns the number of lanes of the register of a vector, which is the count of the components of it when
    /// the value is kept in fields instead of a register.
    /// </summary>
    /// <param name="typ">The type of the vector</param>
    /// <param name="size">The number of components of the vector</param>
    /// <param name="storeVariant">True for the storage variant of the vector</param>
    /// <returns>The number of lanes of the register</returns>
    public static int Lanes(Typ typ, int size, bool storeVariant)
    {
        var reg = Register(typ, size, storeVariant);
        return reg == 0 ? size : reg / (8 * typ.size);
    }

    /// <summary>
    /// Returns the number of lanes of the register of a vector that are padding, 0 when the register is exactly
    /// as wide as the vector and the vector has no register at all.
    /// </summary>
    /// <param name="typ">The type of the vector</param>
    /// <param name="size">The number of components of the vector</param>
    /// <param name="storeVariant">True for the storage variant of the vector</param>
    /// <returns>The number of padding lanes</returns>
    public static int PadLanes(Typ typ, int size, bool storeVariant) => Lanes(typ, size, storeVariant) - size;

    /// <summary>
    /// Builds a result from a raw simd expression. The constructor masks the padding lanes of a register that is
    /// wider than the vector, an expression that keeps them at zero writes the field directly and skips the mask.
    /// </summary>
    /// <param name="simd">True when the vector is backed by a hardware accelerated simd type</param>
    /// <param name="pad">True when the register of the vector has padding lanes</param>
    /// <param name="expr">The raw simd expression of the result</param>
    /// <param name="masked">True when the expression can leave something else than zero in the padding lanes</param>
    /// <returns>The construction of the result</returns>
    public static string Vector(bool simd, bool pad, string expr, bool masked = false) =>
        simd && pad && masked ? $"new({expr})" : $"new() {{ vector = {expr} }}";

    /// <summary>
    /// Joins the part of every component with <paramref name="sep"/>.
    /// </summary>
    /// <param name="size">The number of components of the vector</param>
    /// <param name="get">The part of a single component</param>
    /// <param name="sep">The separator between two components</param>
    /// <returns>The joined parts</returns>
    public static string Join(int size, Func<int, string> get, string sep = ", ")
    {
        var b = new StringBuilder();
        for (var i = 0; i < size; i++)
        {
            if (i != 0) b.Append(sep);
            b.Append(get(i));
        }

        return b.ToString();
    }
}
