using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Coplt.Analyzers.Generators;

/// <summary>
/// Generates the functions of the scalar types described by <see cref="Typ"/>: the members of the <c>math</c>
/// class and the members that are called on a value, which are the members of the extension of the type. Every
/// type gets its own file, the two forms of an operation are written into it together because they are the same
/// operation.
/// <para>The operations and their body are described by <see cref="ScalarOps"/>, their documentation by
/// <see cref="ScalarDocs"/> and the expression of an operation of the BCL by <see cref="VectorScalar"/>, which
/// the vectors use as well.</para>
/// </summary>
[Generator]
public class ScalarGenerator : IIncrementalGenerator
{
    /// <summary>The namespace of the functions.</summary>
    public const string Namespace = "Coplt.Mathematics";

    /// <summary>The name of the class that carries the members that are called on a value.</summary>
    public const string Extension = "ScalarExtensions";

    /// <summary>The attribute of a member, it is inlined into its caller.</summary>
    private const string Attr = "[MethodImpl(256)]";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
        {
            foreach (var typ in Typ.Typs)
            {
                // only a numeric type has functions, the bool vectors are not numeric
                if (!typ.arith) continue;
                ctx.AddSource(
                    $"{Namespace}.math.{typ.compType}.g.cs",
                    SourceText.From(Gen(typ), Encoding.UTF8));
            }
        });
    }

    /// <summary>
    /// Generates the members of the scalar type <paramref name="typ"/>.
    /// </summary>
    /// <param name="typ">The type of the value</param>
    /// <returns>The file</returns>
    private static string Gen(Typ typ)
    {
        var scalar = typ.compType;
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Numerics;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine();
        sb.AppendLine($"namespace {Namespace};");
        sb.AppendLine();

        // the members of the two forms of an operation are the same operation, the static form is the one that
        // the math class carries and the other one is called on a value
        void Members(bool extension)
        {
            var indent = extension ? "        " : "    ";
            var region = "";
            foreach (var op in ScalarOps.Operations)
            {
                if (!ScalarOps.Matches(op, typ)) continue;
                // an operation that does not work on its first parameter has no second form
                if (extension && op.Self < 0) continue;
                if (region != op.Kind)
                {
                    if (region.Length != 0)
                    {
                        sb.AppendLine($"{indent}#endregion");
                        sb.AppendLine();
                    }

                    region = op.Kind;
                    sb.AppendLine($"{indent}#region {ScalarOps.Region(op.Kind)}");
                    sb.AppendLine();
                }

                var parameters = op.ParameterNames(extension);
                var returns = op.Returns.Length == 0 ? scalar : op.Returns.Replace("{s}", scalar);
                var body = op.Source(typ, op.Operands(extension));
                var head = extension
                    ? $"public {returns} {op.Name}({op.Parameters(scalar, extension)})"
                    : $"public static {returns} {op.Name}({op.Parameters(scalar, extension)})";

                ScalarDocs.Emit(sb, indent, op.Name, parameters);
                sb.AppendLine($"{indent}{Attr}");
                // an operation whose body is more than an expression is written out, one statement on a line
                if (body.IndexOf('\n') < 0)
                {
                    var expression = body.EndsWith(";", StringComparison.Ordinal) ? body[..^1] : body;
                    sb.AppendLine($"{indent}{head} => {expression};");
                    sb.AppendLine();
                    continue;
                }

                sb.AppendLine($"{indent}{head}");
                sb.AppendLine($"{indent}{{");
                foreach (var line in body.Split('\n')) sb.AppendLine($"{indent}    {line}");
                sb.AppendLine($"{indent}}}");
                sb.AppendLine();
            }

            if (region.Length != 0)
            {
                sb.AppendLine($"{indent}#endregion");
                sb.AppendLine();
            }
        }

        sb.AppendLine($"public static partial class math");
        sb.AppendLine("{");
        Members(false);
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"public static partial class {Extension}");
        sb.AppendLine("{");
        sb.AppendLine($"    extension({scalar} value)");
        sb.AppendLine("    {");
        Members(true);
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }
}
