using System;
using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Coplt.Analyzers.Generators;

/// <summary>
/// Generates the members of the simd library that shuffle the two registers of a value, the table that
/// dispatches the pattern of a pair of values whose pattern is only known at run time, and the type of the
/// pattern itself. Every combination of the 4 components of the two values is a member of its own whose name
/// holds the pattern of it, so the pattern of a call site is a constant of the member and the instruction of the
/// machine is reached without a branch of the library.
/// <para>The members of the kinds of 4 bytes reach the shuffle of the packed singles of an x86 machine, which
/// takes the low half of the result from the first value and the high half of it from the second one, and the
/// member of the machine names every one of the 4 components of the result itself. The members of the kinds of
/// 8 bytes reach the permute of two sources of the machines of the family of avx512 where the platform holds
/// one, whose index names the component and the value it belongs to, the shuffle of the two lanes of the
/// registers where the platform holds the family of avx, whose control names the component of a lane of a
/// register and the shuffle of the components of the result names the lane of it, and the shuffle of the
/// components of either of the two values beside a selection of the halves of the two results where neither of
/// the two families holds.</para>
/// </summary>
[Generator]
public class SimdShuffleGenerator : IIncrementalGenerator
{
    /// <summary>The namespace the members of the shuffle are emitted into</summary>
    public const string SimdNamespace = "Coplt.Mathematics.Simd";

    /// <summary>The namespace the type of the pattern is emitted into</summary>
    public const string PatternNamespace = "Coplt.Mathematics";

    /// <summary>The name of the type of the pattern of a shuffle, which every member of one takes</summary>
    public const string Lh = "Shuffle42";

    /// <summary>The name of a component of a value by the index of it</summary>
    private static readonly string[] Comp = { "x", "y", "z", "w" };

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
        {
            // the pattern of a shuffle is the name of its member and the value of the type of the pattern, its
            // type is emitted beside the members so that the two of them cannot drift apart
            ctx.AddSource(
                $"{PatternNamespace}.{Lh}.g.cs",
                SourceText.From(GenPattern(), Encoding.UTF8));
            // the 6 members of every pattern are emitted into a file of their own, their table beside them
            ctx.AddSource(
                $"{SimdNamespace}.simd_shuffle.4.2.g.cs",
                SourceText.From(GenMembers(), Encoding.UTF8));
            ctx.AddSource(
                $"{SimdNamespace}.simd_shuffle.4.2.table.g.cs",
                SourceText.From(GenTable(), Encoding.UTF8));
        });
    }

    /// <summary>The name of every pattern of the shuffle of a pair of values of 4 components</summary>
    private static IEnumerable<string> Patterns()
    {
        for (var i = 0; i < 4; i++)
        {
            for (var j = 0; j < 4; j++)
            {
                for (var k = 0; k < 4; k++)
                {
                    for (var l = 0; l < 4; l++)
                    {
                        yield return $"{Comp[i]}{Comp[j]}_{Comp[k]}{Comp[l]}";
                    }
                }
            }
        }
    }

    /// <summary>
    /// Generates the type of the pattern of a shuffle of the two values of 4 components: the 2 first digits of
    /// the name of a value of the type are the components of the low half of the result and the 2 last ones the
    /// components of the high half of it. The value of the type is a constant of the member of its pattern, so
    /// the member that reaches the pattern of it cannot read a pattern that no member names.
    /// </summary>
    /// <returns>The type of the pattern</returns>
    private static string GenPattern()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {PatternNamespace};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// The pattern of the shuffle of 2 values of 4 components");
        sb.AppendLine("/// <para>The 2 first digits of the name of a value are the components of the low half of the result");
        sb.AppendLine("/// of the shuffle and the 2 last ones the components of the high half of it, so the name of a value");
        sb.AppendLine("/// is the name of the member of the shuffle of its pattern.</para>");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public enum {Lh} : byte");
        sb.AppendLine("{");
        foreach (var pattern in Patterns())
        {
            sb.AppendLine($"    {pattern},");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Generates the members of the shuffle: a member of the kinds of 4 bytes reaches the shuffle of the packed
    /// singles of the members of the family of sse, a member of the kinds of 8 bytes reaches the permute of two
    /// sources of the family of avx512 where the platform holds one, the shuffle of the two lanes of the
    /// registers of the value where it holds the family of avx, and the shuffle of the components of the two
    /// values beside the selection of the halves of the two results where neither of the two families holds.
    /// </summary>
    /// <returns>The members of the shuffle</returns>
    private static string GenMembers()
    {
        var sb = new StringBuilder();
        SimdFileHeader(sb);
        sb.AppendLine("public static partial class simd_shuffle");
        sb.AppendLine("{");
        sb.AppendLine();
        foreach (var pattern in Patterns())
        {
            GenSingles(sb, pattern);
            sb.AppendLine();
        }

        foreach (var pattern in Patterns())
        {
            GenDoubles(sb, pattern);
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Generates the 3 members of a pattern whose component is of 4 bytes: the 2 members of the kinds that are
    /// read as the kind of the shuffle themselves forward the call to the member of the single kind of a
    /// component, which reaches the pattern with 1 instruction of the machine of either of the 2 families the
    /// library is built on.
    /// </summary>
    /// <param name="sb">The builder of the file</param>
    /// <param name="pattern">The pattern of the member</param>
    private static void GenSingles(StringBuilder sb, string pattern)
    {
        var (i, j, k, l) = Digits(pattern);
        sb.AppendLine("    [MethodImpl(256)]");
        sb.AppendLine($"    public static Vector128<int> Shuffle_{pattern}(Vector128<int> a, Vector128<int> b) =>");
        sb.AppendLine($"        Shuffle_{pattern}(a.AsSingle(), b.AsSingle()).AsInt32();");
        sb.AppendLine();
        sb.AppendLine("    [MethodImpl(256)]");
        sb.AppendLine($"    public static Vector128<uint> Shuffle_{pattern}(Vector128<uint> a, Vector128<uint> b) =>");
        sb.AppendLine($"        Shuffle_{pattern}(a.AsSingle(), b.AsSingle()).AsUInt32();");
        sb.AppendLine();
        // the shuffle of the packed singles of an x86 machine takes the 2 low components of its result from the
        // low half of the first value and the 2 high ones from the low half of the second one, so the 2 digits of
        // the low half of the pattern name the component of the first value and the 2 digits of the high half the
        // component of the second one: the control of the member is the 2 first digits of it in the 2 low bits of
        // the byte and the 2 last ones in the 2 high bits
        var control = i | (j << 2) | (k << 4) | (l << 6);
        sb.AppendLine("    [MethodImpl(256)]");
        sb.AppendLine($"    public static Vector128<float> Shuffle_{pattern}(Vector128<float> a, Vector128<float> b)");
        sb.AppendLine("    {");
        // the table lookup of an arm machine reads the 16 bytes of its result out of the 32 bytes of the 2
        // registers of the value by the index of every one of them, so every pattern of a value of 4 bytes reaches
        // 1 instruction: the 4 bytes of a component of the result are the 4 bytes of the component of the value
        // that holds it, and the index of a component of the second value names the bytes of it beside the 16 bytes
        // of the register of the first one
        sb.AppendLine("        if (AdvSimd.Arm64.IsSupported)");
        sb.AppendLine("            return Vector128.AsSingle(AdvSimd.Arm64.VectorTableLookup(");
        sb.AppendLine("                (Vector128.AsByte(a), Vector128.AsByte(b)),");
        sb.AppendLine($"                Vector128.Create({ByteIndexes(i, j, k, l)})");
        sb.AppendLine("            ));");
        sb.AppendLine($"        if (Sse.IsSupported) return Sse.Shuffle(a, b, 0b{Binary(control, 8)});");
        GenFallback(sb, "Vector128", "Vector128.Create(0, 0, -1, -1).AsSingle()", i, j, k, l);
        sb.AppendLine("    }");
    }

    /// <summary>
    /// Generates the 3 members of a pattern whose component is of 8 bytes: the 2 members of the kinds that are
    /// read as the kind of the shuffle themselves forward the call to the member of the double kind of a
    /// component.
    /// </summary>
    /// <param name="sb">The builder of the file</param>
    /// <param name="pattern">The pattern of the member</param>
    private static void GenDoubles(StringBuilder sb, string pattern)
    {
        var (i, j, k, l) = Digits(pattern);
        sb.AppendLine("    [MethodImpl(256)]");
        sb.AppendLine($"    public static Vector256<long> Shuffle_{pattern}(Vector256<long> a, Vector256<long> b) =>");
        sb.AppendLine($"        Shuffle_{pattern}(a.AsDouble(), b.AsDouble()).AsInt64();");
        sb.AppendLine();
        sb.AppendLine("    [MethodImpl(256)]");
        sb.AppendLine($"    public static Vector256<ulong> Shuffle_{pattern}(Vector256<ulong> a, Vector256<ulong> b) =>");
        sb.AppendLine($"        Shuffle_{pattern}(a.AsDouble(), b.AsDouble()).AsUInt64();");
        sb.AppendLine();
        sb.AppendLine("    [MethodImpl(256)]");
        sb.AppendLine($"    public static Vector256<double> Shuffle_{pattern}(Vector256<double> a, Vector256<double> b)");
        sb.AppendLine("    {");
        // the permute of two sources of a machine of the family of avx512 names the component and the value of
        // every one of the 4 components of its result in one instruction, so every pattern reaches it: the index
        // of a component of the 2 first values of the table is the index of the component of the value and the
        // index of a component of the 2 last ones is the index of the component of the second value beside 4
        sb.AppendLine("        if (Avx512F.VL.IsSupported)");
        sb.AppendLine($"            return Avx512F.VL.PermuteVar4x64x2(a, Vector256.Create({i}L, {j}L, {k + 4}L, {l + 4}L), b);");
        // the shuffle of the two lanes of the registers of the value takes a component of every one of the two
        // values from every one of the 2 lanes of a register, so it reaches every pattern whose first value
        // reaches its 2 components from a single lane of its register and whose second one does as well
        if (ReachesLanes(i, j) && ReachesLanes(k, l))
        {
            sb.AppendLine("        if (Avx.IsSupported)");
            sb.AppendLine("        {");
            sb.AppendLine($"            var r = Avx.Shuffle(a, b, 0b{Binary(Control(i, j, k, l), 4)});");
            sb.AppendLine($"            return Vector256.Shuffle(r, Vector256.Create({Lane(i, true)}, {Lane(j, true)}, {Lane(k, false)}, {Lane(l, false)}));");
            sb.AppendLine("        }");
        }

        GenFallback(sb, "Vector256", "Vector256.Create(0L, 0L, -1L, -1L).AsDouble()", i, j, k, l);
        sb.AppendLine("    }");
    }

    /// <summary>
    /// Emits the fallback of a pattern: every one of the 2 values shuffles the pair of the components that the
    /// pattern takes from it into the half of the register that the pair reaches in the result, and the two halves
    /// of the two results are joined. The shuffle of a value whose pair is the 2 components of a half of its
    /// register is left out, which is the pair that the value already holds in the half of the result: the 2
    /// components of the low half of the first value and the 2 components of the high half of the second one are
    /// the pairs of the 2 patterns that the machine of the family of sse reaches with one instruction as well, and
    /// the shuffle of the value of 4 bytes of an arm register reaches the 2 components of a half of a register in
    /// one instruction. A pattern that leaves one of the 2 shuffles out joins the half that the shuffle reaches
    /// with the half of the other value itself, which the member that holds a half of the register reaches without
    /// a condition, and a pattern that reaches both of them joins the 2 halves with the selection of the 2 of them,
    /// which names the half of the result of either of the two shuffles.
    /// </summary>
    /// <param name="sb">The builder of the file</param>
    /// <param name="vector">The name of the type of the registers of the 2 values</param>
    /// <param name="condition">The condition of the selection of the 2 halves of the 2 shuffles</param>
    /// <param name="i">The index of the first component of the low half of the result, which the first value holds</param>
    /// <param name="j">The index of the second component of the low half of the result</param>
    /// <param name="k">The index of the first component of the high half of the result, which the second value holds</param>
    /// <param name="l">The index of the second component of the high half of the result</param>
    private static void GenFallback(
        StringBuilder sb, string vector, string condition, int i, int j, int k, int l)
    {
        // the pair of a value that is the 2 components of a half of its register reaches the half of the result
        // that the half of the register reaches without a shuffle of the value, so the shuffle of it is left out
        var low = i == 0 && j == 1;
        var high = k == 2 && l == 3;
        // the pair of every one of the 2 values is the pair that its own value holds, so neither of the 2 shuffles
        // is reached and the 2 halves of the result are the 2 halves of the 2 values themselves
        if (low && high)
        {
            sb.AppendLine("        return a.WithUpper(b.GetUpper());");
            return;
        }

        if (!low && high)
        {
            sb.AppendLine($"        var lo = {vector}.Shuffle(a, {vector}.Create({i}, {j}, 2, 3));");
            sb.AppendLine("        return lo.WithUpper(b.GetUpper());");
            return;
        }

        if (low && !high)
        {
            sb.AppendLine($"        var hi = {vector}.Shuffle(b, {vector}.Create(0, 1, {k}, {l}));");
            sb.AppendLine("        return hi.WithLower(a.GetLower());");
            return;
        }

        // the 2 halves of the result are held by the 2 shuffles, so the selection of the 2 of them joins them,
        // which reaches the 2 components of a half of a register in one instruction
        sb.AppendLine($"        var lo = {vector}.Shuffle(a, {vector}.Create({i}, {j}, 2, 3));");
        sb.AppendLine($"        var hi = {vector}.Shuffle(b, {vector}.Create(0, 1, {k}, {l}));");
        sb.AppendLine($"        return {vector}.ConditionalSelect({condition}, hi, lo);");
    }

    /// <summary>
    /// Generates the 2 members that dispatch the pattern of a pair of values whose pattern is only known at run
    /// time: the pattern of such a pair is a value instead of a part of the name of the member, so the switch of
    /// the value of it is the only way to reach every one of the 256 combinations, which the member of the value
    /// of the pattern of a member is the branch of. The pair of the values of a kind of 4 bytes is dispatched
    /// through the value of 8 components of the same kind, which carries the two of them beside each other, and
    /// the pair of the values of a kind of 8 bytes through the member of the double kind of a component.
    /// </summary>
    /// <returns>The members that dispatch the pattern</returns>
    private static string GenTable()
    {
        var sb = new StringBuilder();
        SimdFileHeader(sb);
        sb.AppendLine("public static partial class simd_shuffle");
        sb.AppendLine("{");
        sb.AppendLine();
        GenTableMember(sb, "Vector128<float>");
        sb.AppendLine();
        GenTableMember(sb, "Vector256<double>");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Generates the member that dispatches the pattern of a pair of values of the type of a register: the
    /// pattern is a value instead of a part of the name of the member, so the switch of it is the only way to
    /// reach every one of the 256 combinations and the member of the value of it is the branch of the switch.
    /// </summary>
    /// <param name="sb">The builder of the file</param>
    /// <param name="type">The type of the vectors of the pair</param>
    private static void GenTableMember(StringBuilder sb, string type)
    {
        sb.AppendLine("    [MethodImpl(256)]");
        sb.AppendLine($"    public static {type} Shuffle({type} a, {type} b, {Lh} lh)");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (lh)");
        sb.AppendLine("        {");
        foreach (var pattern in Patterns())
        {
            sb.AppendLine($"            case {Lh}.{pattern}:");
            sb.AppendLine($"                return Shuffle_{pattern}(a, b);");
        }

        sb.AppendLine("            default:");
        sb.AppendLine("                throw new ArgumentOutOfRangeException(nameof(lh), lh, null);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    /// <summary>
    /// Emits the header of a file of the members of the shuffle.
    /// </summary>
    /// <param name="sb">The builder of the file</param>
    private static void SimdFileHeader(StringBuilder sb)
    {
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Runtime.Intrinsics;");
        sb.AppendLine("using System.Runtime.Intrinsics.Arm;");
        sb.AppendLine("using System.Runtime.Intrinsics.X86;");
        sb.AppendLine();
        sb.AppendLine($"namespace {SimdNamespace};");
        sb.AppendLine();
    }

    /// <summary>
    /// Returns the 4 indexes of the components of the pattern of a member: the 2 first ones are the components
    /// of the low half of the result and the 2 last ones the components of the high half of it.
    /// </summary>
    /// <param name="pattern">The pattern of the member</param>
    /// <returns>The index of every one of the 4 components of the pattern</returns>
    private static (int I, int J, int K, int L) Digits(string pattern) => (
        "xyzw".IndexOf(pattern[0]),
        "xyzw".IndexOf(pattern[1]),
        "xyzw".IndexOf(pattern[3]),
        "xyzw".IndexOf(pattern[4]));

    /// <summary>
    /// True when the shuffle of the two lanes of the registers of a value reaches a pair of components that the
    /// pair of the indexes of a value names: the member of the machine takes a component of the value from every
    /// one of the 2 lanes of the register of it, so a pair whose 2 components are not the same component of the
    /// value reaches them from a single lane only where the two of them are the 2 components of a lane.
    /// </summary>
    /// <param name="p">The index of the first component of the pair</param>
    /// <param name="q">The index of the second component of the pair</param>
    /// <returns>True when the member of the machine reaches the pair</returns>
    private static bool ReachesLanes(int p, int q) =>
        !(p < 2 && q < 2 && p != q) && !(p >= 2 && q >= 2 && p != q);

    /// <summary>
    /// Returns the control of the shuffle of the two lanes of the registers of a value: the 2 low bits of the
    /// control name the component of the low lane of the first value, the third one the component of the low lane
    /// of the second value, the fourth one the component of the high lane of the first value and the 2 high ones
    /// the component of the high lane of the second one.
    /// </summary>
    /// <param name="p">The index of the first component of the first value</param>
    /// <param name="q">The index of the second component of the first value</param>
    /// <param name="r">The index of the first component of the second value</param>
    /// <param name="s">The index of the second component of the second value</param>
    /// <returns>The control of the member of the machine</returns>
    private static int Control(int p, int q, int r, int s)
    {
        // a component of the low lane of a value, which is the one the low bit of its half names, and a
        // component of the high lane of it, which is the one the high bit of its half names: a half that no
        // component of the pattern reaches names the low component of it, which the shuffle of the components
        // of the result does not read
        var aLow = p < 2 ? p : q < 2 ? q : 0;
        var aHigh = p >= 2 ? p : q >= 2 ? q : 2;
        var bLow = r < 2 ? r : s < 2 ? s : 0;
        var bHigh = r >= 2 ? r : s >= 2 ? s : 2;
        return (aLow & 1) | ((bLow & 1) << 1) | ((aHigh & 1) << 2) | ((bHigh & 1) << 3);
    }

    /// <summary>
    /// Returns the lane of the register of the value that the shuffle of the components of the result reads the
    /// component of an index from: the 2 components of the low half of the result are the component of the low
    /// lane of the first value and the component of the low lane of the second one, and the 2 components of the
    /// high half of it the component of the high lane of the two of them.
    /// </summary>
    /// <param name="p">The index of the component of one of the two values</param>
    /// <param name="first">True for the first value, false for the second one</param>
    /// <returns>The lane of the register of the value that holds the component</returns>
    private static int Lane(int p, bool first) => first ? (p < 2 ? 0 : 2) : (p < 2 ? 1 : 3);

    /// <summary>
    /// Returns the index of every one of the 16 bytes of the result of the table lookup of an arm machine: the 4
    /// bytes of a component of the first value are the 4 bytes of the component of it that the index names and the
    /// 4 bytes of a component of the second value are the bytes of it beside the 16 bytes of the register of the
    /// first one.
    /// </summary>
    /// <param name="i">The index of the first component of the low half of the result</param>
    /// <param name="j">The index of the second component of the low half of the result</param>
    /// <param name="k">The index of the first component of the high half of the result</param>
    /// <param name="l">The index of the second component of the high half of the result</param>
    /// <returns>The index of the 4 bytes of every one of the 4 components of the result</returns>
    private static string ByteIndexes(int i, int j, int k, int l)
    {
        var sb = new StringBuilder();
        var bases = new[] { i * 4, j * 4, 16 + k * 4, 16 + l * 4 };
        foreach (var start in bases)
        {
            for (var b = 0; b < 4; b++)
            {
                if (sb.Length > 0) sb.Append(", ");
                sb.Append($"(byte){start + b}");
            }
        }

        return sb.ToString();
    }

    /// <summary>The binary form of a control, which the member of the machine takes as the value of an immediate</summary>
    private static string Binary(int value, int digits) => Convert.ToString(value, 2).PadLeft(digits, '0');
}
