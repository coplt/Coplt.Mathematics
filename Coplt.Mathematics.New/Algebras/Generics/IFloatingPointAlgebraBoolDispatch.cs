namespace Coplt.Mathematics.Algebras.Generics;

/// <summary>
/// The dispatch of the bool value of a floating point value to the visitor that builds it
/// <para>It is the dispatch of the value beside the one of the kind of it: the bool value of a value has the
/// same shape as it, which the type of the value does not name, so the dispatch of it names the type of the
/// bool value as well, and every floating point value of the library implements it</para>
/// <para>The type of a single component of the bool value is not a part of it: the visitor of the value names
/// it, which the shape of the value decides and the dispatch of it does not</para>
/// <para>The interfaces of the visitors are generated by
/// <c>Coplt.Analyzers.Generators.AlgebraVisitorGenerator</c>, and the one of the visitor that builds the bool
/// value of a value is the one of a shape that takes the value alone</para>
/// </summary>
/// <typeparam name="TSelf">The type of the value itself</typeparam>
/// <typeparam name="TBool">The type of the bool value that has the same shape as the value</typeparam>
public interface IFloatingPointAlgebraBoolDispatch<TSelf, TBool> :
    IFloatingPointAlgebraDispatch<TSelf>
    where TSelf : unmanaged, IFloatingPointAlgebraBoolDispatch<TSelf, TBool>
    where TBool : unmanaged, IBoolMatrix<TBool>
{
    /// <summary>
    /// Hands the value of <paramref name="self"/> to <typeparamref name="V"/>, which builds the bool value that
    /// has the same shape as it
    /// </summary>
    /// <typeparam name="V">The type of the visitor that reaches the value</typeparam>
    /// <param name="self">The value to hand over</param>
    /// <returns>The bool value the visitor built</returns>
    public static abstract TBool Visit_Self_Bool<V>(in TSelf self)
        where V : IFloatingPointAlgebraVisitor_Self_Bool<V>;
}
